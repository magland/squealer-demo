// Gaussian process fit to thermometer readings (Section 2.4 of the paper):
//   y_i ~ normal(f(t_i), sigma),  f ~ GP(98.6, k),  k(t, t') = alpha exp(-(t - t')^2 / (2 ell^2)),
// with theta = (alpha, ell, sigma) fit by maximizing the log marginal likelihood.
// Time t is the fraction of the 6:00-12:00 window, x = 6 + 6t hours.
//
// Grabbing the curve at (x*, y*) conditions f(x*) = y* exactly. This is the limit of
// the paper's pseudo-data point with variance 1e-6 (its eq. 10): theta* maximizes the
// marginal likelihood of the data and the pinned values together, and the curve is the
// posterior mean of f given both, so it passes through every pin.
//
// The data are simulated to resemble the paper's Figure 11a (the paper's data are not
// published): a rise from about 98.95 to 100 F, then readings near 100 F with a few
// above 100.2 F in the last 45 minutes. Generated by scripts/gen_temperature.py.
