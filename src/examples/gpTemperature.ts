const MU = 98.6;
const X0 = 6;
const SPAN = 6;
const toT = (x: number) => (x - X0) / SPAN;
const N = T.length;
const TD = T.map(toT);
const LOG2PI = Math.log(2 * Math.PI);
const N_DRAWS = 400;
const N_CURVES = 30;
const GRID = 121;

type Theta = [number, number, number]; // alpha, ell, sigma

interface Points {
  t: number[];
  r: number[]; // value minus prior mean
  noise: number[]; // observation variance
}

function pointsFor(pins: Pin[], theta: Theta): Points {
  const [alpha, , sigma] = theta;
  return {
    t: [...TD, ...pins.map((p) => toT(p.x))],
    r: [...Y.map((y) => y - MU), ...pins.map((p) => p.y - MU)],
    // Pins are noise-free; a tiny jitter keeps the matrix invertible.
    noise: [...TD.map(() => sigma * sigma), ...pins.map(() => 1e-9 * alpha)],
  };
}

const kern = (a: number, b: number, alpha: number, ell: number) => alpha * Math.exp(-((a - b) ** 2) / (2 * ell * ell));

function covChol(pts: Points, alpha: number, ell: number): Chol | null {
  const n = pts.t.length;
  const A = new Float64Array(n * n);
  for (let i = 0; i < n; i++) {
    for (let j = 0; j <= i; j++) {
      const v = kern(pts.t[i], pts.t[j], alpha, ell);
      A[i * n + j] = v;
      A[j * n + i] = v;
    }
    A[i * n + i] += pts.noise[i];
  }
  return cholesky(A, n);
}

// log p(values | theta), the (N + pins)-dimensional normal marginal likelihood.
function logML(pins: Pin[], theta: Theta): number {
  const pts = pointsFor(pins, theta);
  const c = covChol(pts, theta[0], theta[1]);
  if (!c) return -Infinity;
  const z = forward(c, pts.r);
  let q = 0;
  for (const v of z) q += v * v;
  return -0.5 * q - 0.5 * logDet(c) - 0.5 * pts.t.length * LOG2PI;
}

const toTheta = (u: number[]): Theta => [Math.exp(u[0]), Math.exp(u[1]), Math.exp(u[2])];

// Hyperparameters in log scale; 1e-5 in log theta is far below what the display can show.
function fitTheta(pins: Pin[], u0: number[], fine = true): number[] {
  const f = (u: number[]) => logML(pins, toTheta(u));
  if (fine) return maximize(f, u0, 0.05);
  return maximize(f, u0, 0.01, { tolF: 1e-10, tolX: 1e-5, restart: false });
}

// Posterior mean of f given data and pins.
function meanCurve(pins: Pin[], theta: Theta): (x: number) => number {
  const pts = pointsFor(pins, theta);
  const c = covChol(pts, theta[0], theta[1])!;
  const w = cholSolve(c, pts.r);
  const [alpha, ell] = theta;
  return (x) => {
    const t = toT(x);
    let s = MU;
    for (let j = 0; j < pts.t.length; j++) s += kern(t, pts.t[j], alpha, ell) * w[j];
    return s;
  };
}

// 1/2 d^T V^{-1} d: how far the pins sit from the data-only posterior of f under theta,
// in posterior sd. d = y* - E(f(x*) | y), V = cov(f(x*) | y).
function pinSurprise(pins: Pin[], theta: Theta): number {
  if (pins.length === 0) return 0;
  const [alpha, ell] = theta;
  const data = pointsFor([], theta);
  const c = covChol(data, alpha, ell)!;
  const w = cholSolve(c, data.r);
  const P = pins.length;
  const tp = pins.map((p) => toT(p.x));
  const Zs = tp.map((t) => forward(c, TD.map((td) => kern(t, td, alpha, ell))));
  const V = new Float64Array(P * P);
  const d = new Float64Array(P);
  for (let a = 0; a < P; a++) {
    let m = MU;
    for (let j = 0; j < N; j++) m += kern(tp[a], TD[j], alpha, ell) * w[j];
    d[a] = pins[a].y - m;
    for (let b = 0; b < P; b++) {
      let s = kern(tp[a], tp[b], alpha, ell);
      for (let j = 0; j < N; j++) s -= Zs[a][j] * Zs[b][j];
      V[a * P + b] = s + (a === b ? 1e-9 * alpha : 0);
    }
  }
  const cv = cholesky(V, P);
  if (!cv) return Infinity;
  const z = forward(cv, d);
  let q = 0;
  for (const v of z) q += v * v;
  return 0.5 * q;
}

// Draws of f on a grid from its posterior given the data at theta.
function fDraws(theta: Theta, S: number): ((x: number) => number)[] {
  const [alpha, ell] = theta;
  const data = pointsFor([], theta);
  const c = covChol(data, alpha, ell)!;
  const w = cholSolve(c, data.r);
  const xs = Array.from({ length: GRID }, (_, i) => X0 + (SPAN * i) / (GRID - 1));
  const ts = xs.map(toT);
  const mean = ts.map((t) => MU + TD.reduce((s, td, j) => s + kern(t, td, alpha, ell) * w[j], 0));
  const Zs = ts.map((t) => forward(c, TD.map((td) => kern(t, td, alpha, ell))));
  const C = new Float64Array(GRID * GRID);
  for (let a = 0; a < GRID; a++) {
    for (let b = 0; b <= a; b++) {
      let s = kern(ts[a], ts[b], alpha, ell);
      for (let j = 0; j < N; j++) s -= Zs[a][j] * Zs[b][j];
      C[a * GRID + b] = s;
      C[b * GRID + a] = s;
    }
    C[a * GRID + a] += 1e-7 * alpha;
  }
  const L = cholesky(C, GRID)!.L;
  const normal = normalSampler(7);
  const out: ((x: number) => number)[] = [];
  for (let s = 0; s < S; s++) {
    const z = Array.from({ length: GRID }, normal);
    const f = mean.map((m, i) => {
      let v = m;
      for (let k = 0; k <= i; k++) v += L[i * GRID + k] * z[k];
      return v;
    });
    out.push((x) => {
      const p = ((x - X0) / SPAN) * (GRID - 1);
      const i = Math.max(0, Math.min(GRID - 2, Math.floor(p)));
      const u = p - i;
      return f[i] * (1 - u) + f[i + 1] * u;
    });
  }
  return out;
}

function pointLL(curve: (x: number) => number, sigma: number): number[] {
  return T.map((x, i) => {
    const e = (Y[i] - curve(x)) / sigma;
    return -0.5 * e * e - Math.log(sigma) - 0.5 * LOG2PI;
  });
}

const fmtTime = (x: number) => {
  const total = Math.round(x * 60);
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
};

export function gpTemperatureExample(): Example {
  const uHat = fitTheta([], [Math.log(0.5), Math.log(0.2), Math.log(0.1)]);
  const thetaHat = toTheta(uHat);
  const mlHat = logML([], thetaHat);
  const solution = (pins: Pin[], u: number[]): Solution => {
    const theta = toTheta(u);
    const curve = meanCurve(pins, theta);
    const ml = logML([], theta);
    const hyper = mlHat - ml;
    const surprise = pinSurprise(pins, theta);
    return {
      theta,
      curve,
      totals: [ml],
      pointLL: pointLL(curve, theta[2]),
      cost: hyper + surprise,
      costParts: pins.length
        ? [
            { name: "from α, ℓ, σ", value: hyper },
            { name: "from f at pins", value: surprise },
          ]
        : [],
      maxViolation: 0,
      warm: u,
    };
  };
  const hat = solution([], uHat);
  const cov = laplaceCovariance((u) => logML([], toTheta(u)), uHat);
  const dashDraws = mvnDraws(uHat, cov, N_DRAWS).map((u) => {
    const theta = toTheta(u);
    return { theta, totals: [logML([], theta)] };
  });
  return {
    id: "gp-temperature",
    title: "Body temperature (Gaussian process)",
    description:
      "Simulated thermometer readings every few minutes from 6:00 to 12:00, fit with a Gaussian process with squared exponential kernel. Simulated to resemble the paper's Figure 11a.",
    xLabel: "Time",
    yLabel: "Temperature (°F)",
    xDomain: [6, 12],
    yDomain: [98.8, 100.5],
    formatX: fmtTime,
    xTicks: [6, 7, 8, 9, 10, 11, 12],
    data: T.map((x, i) => ({ x, y: Y[i] })),
    paramNames: ["alpha", "ell", "sigma"],
    totalNames: ["log marg lik"],
    maxPins: 8,
    pinNote:
      "Each pin fixes the true temperature f exactly at that time, and α, ℓ and σ are re-fit by maximizing the marginal likelihood of the readings and the pins together.",
    drawNote: `${N_DRAWS} draws from a normal approximation to the marginal likelihood in log θ at θ̂`,
    clampX: (x) => Math.min(12, Math.max(6, x)),
    hat,
    drawCurves: fDraws(thetaHat, N_CURVES),
    dashDraws,
    solve(pins: Pin[], warm: unknown) {
      if (pins.length === 0) return hat;
      return solution(pins, fitTheta(pins, warm as number[], false));
    },
  };
}
